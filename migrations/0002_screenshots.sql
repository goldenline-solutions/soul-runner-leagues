-- Box score screenshots read by the ingest pipeline.
-- One row per unique image (by SHA-256) so re-uploads never pay for a second model call.
-- The image itself is stored in the row (hosts like Vercel have no persistent disk).
CREATE TABLE screenshots (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sha256 TEXT NOT NULL UNIQUE,
  mime TEXT NOT NULL,
  image BYTEA NOT NULL,
  extracted TEXT,                 -- model JSON after post-processing
  warnings TEXT NOT NULL DEFAULT '[]',
  game_id INTEGER REFERENCES games(id) ON DELETE SET NULL,
  created_at TEXT NOT NULL DEFAULT to_char(timezone('utc', now()), 'YYYY-MM-DD HH24:MI:SS')
);
CREATE INDEX screenshots_game ON screenshots(game_id);
