-- Other names a player goes by (an old or new Steam name, an in-game name). The screenshot reader
-- and the box score form match these as well as the Discord and Steam tags, so a renamed player
-- still lands on the same profile.
CREATE TABLE player_aliases (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  player_id INTEGER NOT NULL REFERENCES players(id) ON DELETE CASCADE,
  alias TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- A name points at one player only.
CREATE UNIQUE INDEX player_aliases_name ON player_aliases (lower(alias));
CREATE INDEX player_aliases_player ON player_aliases (player_id);
