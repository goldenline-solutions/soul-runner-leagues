-- Soul Runner NBA 2k27 PC Leagues: core schema (PostgreSQL)
-- Timestamps are stored as UTC text 'YYYY-MM-DD HH:MM:SS' so the site can show them as-is.

CREATE TABLE leagues (
  id TEXT PRIMARY KEY,               -- 'premier' | 'affiliate'
  name TEXT NOT NULL,
  season_name TEXT NOT NULL,
  blurb TEXT NOT NULL DEFAULT '',
  sort INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE teams (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  league_id TEXT NOT NULL REFERENCES leagues(id),
  name TEXT NOT NULL,
  owner_coach TEXT NOT NULL DEFAULT '',
  stream_url TEXT NOT NULL DEFAULT '',
  sponsors TEXT NOT NULL DEFAULT '',
  affiliated_teams TEXT NOT NULL DEFAULT '',
  UNIQUE (league_id, name)
);

-- One row per human player, keyed by Discord tag (case-insensitive).
CREATE TABLE players (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  discord_tag TEXT NOT NULL,
  steam_tag TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL DEFAULT to_char(timezone('utc', now()), 'YYYY-MM-DD HH24:MI:SS')
);
CREATE UNIQUE INDEX players_tag ON players (lower(discord_tag));

-- Seven roster slots per team: PG, SG, SF, PF, C, 6TH, 7TH.
CREATE TABLE roster_slots (
  team_id INTEGER NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
  slot TEXT NOT NULL,
  player_id INTEGER REFERENCES players(id) ON DELETE SET NULL,
  PRIMARY KEY (team_id, slot)
);

CREATE TABLE weeks (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  league_id TEXT NOT NULL REFERENCES leagues(id),
  number INTEGER NOT NULL,
  phase TEXT NOT NULL DEFAULT '',     -- e.g. FIRST MEETINGS
  start_date TEXT,                    -- ISO date of the Friday
  date_label TEXT NOT NULL DEFAULT '',
  UNIQUE (league_id, number)
);

-- A best-of-3 matchup. Regular season series belong to a week;
-- playoff series use stage + slot and may have teams assigned later.
CREATE TABLE series (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  league_id TEXT NOT NULL REFERENCES leagues(id),
  week_id INTEGER REFERENCES weeks(id),
  stage TEXT NOT NULL DEFAULT 'regular',   -- regular | qf | sf | final
  slot INTEGER NOT NULL DEFAULT 0,
  label TEXT NOT NULL DEFAULT '',
  home_team_id INTEGER REFERENCES teams(id),
  away_team_id INTEGER REFERENCES teams(id)
);
CREATE INDEX series_week ON series(week_id);

CREATE TABLE games (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  series_id INTEGER NOT NULL REFERENCES series(id) ON DELETE CASCADE,
  game_number INTEGER NOT NULL CHECK (game_number BETWEEN 1 AND 3),
  home_score INTEGER NOT NULL DEFAULT 0,
  away_score INTEGER NOT NULL DEFAULT 0,
  forfeit TEXT CHECK (forfeit IN ('home', 'away')),  -- side that forfeited
  created_at TEXT NOT NULL DEFAULT to_char(timezone('utc', now()), 'YYYY-MM-DD HH24:MI:SS'),
  updated_at TEXT NOT NULL DEFAULT to_char(timezone('utc', now()), 'YYYY-MM-DD HH24:MI:SS'),
  UNIQUE (series_id, game_number)
);

CREATE TABLE box_scores (
  game_id INTEGER NOT NULL REFERENCES games(id) ON DELETE CASCADE,
  player_id INTEGER NOT NULL REFERENCES players(id),
  team_id INTEGER NOT NULL REFERENCES teams(id),
  pts INTEGER NOT NULL DEFAULT 0,
  reb INTEGER NOT NULL DEFAULT 0,
  ast INTEGER NOT NULL DEFAULT 0,
  stl INTEGER NOT NULL DEFAULT 0,
  blk INTEGER NOT NULL DEFAULT 0,
  tov INTEGER NOT NULL DEFAULT 0,
  pf INTEGER NOT NULL DEFAULT 0,
  fgm INTEGER NOT NULL DEFAULT 0,
  fga INTEGER NOT NULL DEFAULT 0,
  tpm INTEGER NOT NULL DEFAULT 0,
  tpa INTEGER NOT NULL DEFAULT 0,
  ftm INTEGER NOT NULL DEFAULT 0,
  fta INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (game_id, player_id)
);
CREATE INDEX box_player ON box_scores(player_id);

-- Registration and sponsorship submissions. Private: admin only.
CREATE TABLE registrations (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind TEXT NOT NULL CHECK (kind IN ('player', 'owner', 'sponsor')),
  data TEXT NOT NULL,                      -- JSON payload
  status TEXT NOT NULL DEFAULT 'new',      -- new | approved | archived
  created_at TEXT NOT NULL DEFAULT to_char(timezone('utc', now()), 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE news (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  body TEXT NOT NULL,
  published_at TEXT NOT NULL DEFAULT to_char(timezone('utc', now()), 'YYYY-MM-DD HH24:MI:SS')
);

-- One vote per award per visitor (anonymous cookie id).
CREATE TABLE award_votes (
  award TEXT NOT NULL CHECK (award IN ('mvp', 'dpoy')),
  voter_id TEXT NOT NULL,
  player_id INTEGER NOT NULL REFERENCES players(id) ON DELETE CASCADE,
  updated_at TEXT NOT NULL DEFAULT to_char(timezone('utc', now()), 'YYYY-MM-DD HH24:MI:SS'),
  PRIMARY KEY (award, voter_id)
);

-- Free-form site settings (All-Star rosters, score, etc.) as JSON text.
CREATE TABLE settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

-- Login and registration throttling. Lives in the database because serverless
-- instances don't share memory.
CREATE TABLE rate_limits (
  key TEXT PRIMARY KEY,
  count INTEGER NOT NULL,
  reset_at TIMESTAMPTZ NOT NULL
);
