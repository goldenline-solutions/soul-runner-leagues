-- Player lines from solo queue result screenshots. Like scrim_box_scores: kept apart from
-- box_scores, so solo games never count toward league stats, standings or awards.
-- Rows are written when the result is reported (src/solo.js, reportResult).
ALTER TABLE solo_matches ADD COLUMN screenshot_id INTEGER REFERENCES screenshots(id) ON DELETE SET NULL;

CREATE TABLE solo_box_scores (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  match_id INTEGER NOT NULL REFERENCES solo_matches(id) ON DELETE CASCADE,
  side TEXT NOT NULL CHECK (side IN ('A', 'B')),               -- Team A or Team B of the solo match
  player_id INTEGER REFERENCES players(id) ON DELETE SET NULL,  -- set when the name matched a league player
  name TEXT NOT NULL,                                           -- the name as read from the screenshot
  pts INTEGER NOT NULL DEFAULT 0,
  reb INTEGER NOT NULL DEFAULT 0,
  ast INTEGER NOT NULL DEFAULT 0,
  stl INTEGER NOT NULL DEFAULT 0,
  blk INTEGER NOT NULL DEFAULT 0,
  tov INTEGER NOT NULL DEFAULT 0,
  pf INTEGER NOT NULL DEFAULT 0,
  fgm INTEGER NOT NULL DEFAULT 0,
  fga INTEGER NOT NULL DEFAULT 0,
  tpm INTEGER NOT NULL DEFAULT 0,
  tpa INTEGER NOT NULL DEFAULT 0,
  ftm INTEGER NOT NULL DEFAULT 0,
  fta INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX solo_box_match ON solo_box_scores (match_id);
CREATE INDEX solo_box_player ON solo_box_scores (player_id);
