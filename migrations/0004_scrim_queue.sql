-- Team scrim queue: teams mark themselves ready, the matcher pairs them, the bot opens a private
-- thread. Nothing here touches NBA 2K. The service layer is src/scrim.js.
-- These tables use real timestamps (TIMESTAMPTZ) because the matcher compares them with now().

-- One row per Discord account, created the first time someone uses the bot or logs in on the site.
CREATE TABLE users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  discord_id TEXT NOT NULL UNIQUE,
  discord_name TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE teams ADD COLUMN discord_role_id TEXT;
ALTER TABLE teams ADD COLUMN skill_rating INTEGER NOT NULL DEFAULT 1000;

-- Who may act for a team. A person is on one team; a team may have more than one captain.
CREATE TABLE team_members (
  team_id INTEGER NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
  role TEXT NOT NULL DEFAULT 'player' CHECK (role IN ('captain', 'player', 'sub')),
  PRIMARY KEY (team_id, user_id)
);

CREATE TABLE queue_entries (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  team_id INTEGER NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
  queued_by_user_id INTEGER NOT NULL REFERENCES users(id),
  mode TEXT NOT NULL CHECK (mode IN ('scrim', 'ranked')),   -- scrim is unrated
  team_size INTEGER NOT NULL CHECK (team_size BETWEEN 1 AND 5),
  available_from TIMESTAMPTZ NOT NULL DEFAULT now(),
  available_until TIMESTAMPTZ NOT NULL DEFAULT now() + interval '60 minutes',
  skill_min INTEGER,
  skill_max INTEGER,
  status TEXT NOT NULL DEFAULT 'waiting' CHECK (status IN ('waiting', 'matched', 'cancelled', 'expired')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- A team has at most one waiting entry, even if two requests race.
CREATE UNIQUE INDEX queue_one_waiting ON queue_entries (team_id) WHERE status = 'waiting';

CREATE TABLE matches (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mode TEXT NOT NULL CHECK (mode IN ('scrim', 'ranked')),
  team_size INTEGER NOT NULL,
  team_a_id INTEGER NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
  team_b_id INTEGER NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
  queue_entry_a_id INTEGER REFERENCES queue_entries(id) ON DELETE SET NULL,
  queue_entry_b_id INTEGER REFERENCES queue_entries(id) ON DELETE SET NULL,
  status TEXT NOT NULL DEFAULT 'pending_accept' CHECK (status IN
    ('pending_accept', 'accepted', 'in_progress', 'awaiting_result', 'completed', 'disputed', 'cancelled')),
  team_a_accepted BOOLEAN NOT NULL DEFAULT false,
  team_b_accepted BOOLEAN NOT NULL DEFAULT false,
  cancel_reason TEXT,
  host_team_id INTEGER REFERENCES teams(id) ON DELETE SET NULL,
  scheduled_for TIMESTAMPTZ,              -- for matches booked ahead; unused so far
  discord_thread_id TEXT,                 -- the private thread for both teams
  announced_status TEXT,                  -- last status the bot posted in the thread
  thread_archived BOOLEAN NOT NULL DEFAULT false,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  accepted_at TIMESTAMPTZ,
  completed_at TIMESTAMPTZ
);
CREATE INDEX matches_status ON matches (status);

CREATE TABLE match_results (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  match_id INTEGER NOT NULL UNIQUE REFERENCES matches(id) ON DELETE CASCADE,
  winner_team_id INTEGER NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
  team_a_score INTEGER NOT NULL,
  team_b_score INTEGER NOT NULL,
  screenshot_id INTEGER REFERENCES screenshots(id) ON DELETE SET NULL,  -- served at /api/screenshots/:id
  submitted_by_user_id INTEGER NOT NULL REFERENCES users(id),
  verified_by_user_id INTEGER REFERENCES users(id),   -- null when a commissioner confirmed on the site
  verified BOOLEAN NOT NULL DEFAULT false,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
