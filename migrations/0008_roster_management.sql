-- Roster management from Discord (src/roster.js, bot/roster.js). Rosters stay where the site
-- already reads them (roster_slots); this adds what the bot needs to manage them safely.

-- The Discord account behind a player record, so signing works on the member, not on a typed name.
ALTER TABLE players ADD COLUMN discord_id TEXT;
CREATE UNIQUE INDEX players_discord_id ON players (discord_id) WHERE discord_id IS NOT NULL;
-- In the free agent pool: looking for a team. Set by /roster freeagent and by a release that
-- leaves the player on no roster; cleared when they are signed.
ALTER TABLE players ADD COLUMN free_agent BOOLEAN NOT NULL DEFAULT FALSE;

-- Every signing, release and move, so "who did that and when" has an answer.
CREATE TABLE roster_moves (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  player_id INTEGER NOT NULL REFERENCES players(id) ON DELETE CASCADE,
  action TEXT NOT NULL CHECK (action IN ('sign', 'release', 'move', 'free_agent')),
  from_team_id INTEGER REFERENCES teams(id) ON DELETE SET NULL,
  to_team_id INTEGER REFERENCES teams(id) ON DELETE SET NULL,
  by_discord_id TEXT,                              -- the commissioner who ran the command
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX roster_moves_player ON roster_moves (player_id);
