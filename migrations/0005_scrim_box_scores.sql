-- Player lines from scrim result screenshots. Kept apart from box_scores on purpose: league
-- stats, standings and awards only ever read box_scores, so scrims never count toward them.
-- Rows are written when a result is reported (src/scrim.js, reportResult). Count a row as a real
-- stat only when its match is 'completed'; a disputed or unconfirmed result keeps its rows too.
CREATE TABLE scrim_box_scores (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  match_id INTEGER NOT NULL REFERENCES matches(id) ON DELETE CASCADE,
  team_id INTEGER NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
  player_id INTEGER REFERENCES players(id) ON DELETE SET NULL,  -- set when the name matched a league player
  name TEXT NOT NULL,                                           -- the name as read from the screenshot
  pts INTEGER NOT NULL DEFAULT 0,
  reb INTEGER NOT NULL DEFAULT 0,
  ast INTEGER NOT NULL DEFAULT 0,
  stl INTEGER NOT NULL DEFAULT 0,
  blk INTEGER NOT NULL DEFAULT 0,
  tov INTEGER NOT NULL DEFAULT 0,
  pf INTEGER NOT NULL DEFAULT 0,
  fgm INTEGER NOT NULL DEFAULT 0,
  fga INTEGER NOT NULL DEFAULT 0,
  tpm INTEGER NOT NULL DEFAULT 0,
  tpa INTEGER NOT NULL DEFAULT 0,
  ftm INTEGER NOT NULL DEFAULT 0,
  fta INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX scrim_box_match ON scrim_box_scores(match_id);
CREATE INDEX scrim_box_player ON scrim_box_scores(player_id);
