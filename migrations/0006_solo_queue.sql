-- Solo queue: single players queue with the positions they play (read from their Discord roles),
-- and the matcher seats ten of them into two teams with one PG, SG, LOCK, BACKEND and C each.
-- Separate from the team scrim queue (queue_entries, matches). See src/solo.js.
CREATE TABLE solo_matches (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  status TEXT NOT NULL DEFAULT 'pending_accept'
    CHECK (status IN ('pending_accept', 'in_progress', 'completed', 'cancelled')),
  cancel_reason TEXT,
  team_a_score INTEGER,
  team_b_score INTEGER,
  reported_by_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  discord_thread_id TEXT,
  announced_status TEXT,                           -- last status the bot posted in the thread
  thread_archived BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  started_at TIMESTAMPTZ,                          -- when the tenth player accepted
  completed_at TIMESTAMPTZ
);

-- One row per time a player queues. Once seated, the row also says where: match, side and position.
CREATE TABLE solo_queue_entries (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  positions TEXT NOT NULL,                         -- what they can play, comma separated: 'PG,SG'
  status TEXT NOT NULL DEFAULT 'waiting' CHECK (status IN ('waiting', 'matched', 'cancelled', 'expired')),
  available_until TIMESTAMPTZ NOT NULL DEFAULT now() + interval '60 minutes',
  match_id INTEGER REFERENCES solo_matches(id) ON DELETE SET NULL,
  side TEXT CHECK (side IN ('A', 'B')),
  position TEXT,                                   -- the one position they were given
  accepted BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX solo_one_waiting ON solo_queue_entries (user_id) WHERE status = 'waiting';
CREATE INDEX solo_entries_match ON solo_queue_entries (match_id);
