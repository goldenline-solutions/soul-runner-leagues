-- A profile claim waits for a commissioner: the request sits here until it is approved (the
-- player record is then linked to the Discord account) or rejected.
CREATE TABLE profile_claims (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  player_id INTEGER NOT NULL REFERENCES players(id) ON DELETE CASCADE,
  discord_id TEXT NOT NULL,
  discord_name TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  decided_at TIMESTAMPTZ
);
-- One open request per Discord account.
CREATE UNIQUE INDEX profile_claims_one_pending ON profile_claims (discord_id) WHERE status = 'pending';
